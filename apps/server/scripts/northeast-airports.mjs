#!/usr/bin/env node
// Regenerates apps/server/src/flights/northeast-airports.ts.
//
// 1. Reads Cattn/clovis's airport list (IATA code, city, name; large + scheduled-medium airports).
// 2. Reads OurAirports' airports.csv for coordinates and ISO region.
// 3. Keeps the Clovis airports in the US Census Northeast (CT, ME, MA, NH, RI, VT, NJ, NY, PA)
//    and writes them, with [lng, lat] coordinates, to the generated module.
//
// Usage (from apps/server):  npm run airports:northeast
//   --lookup BWI,ORD   also print OurAirports coordinates for any codes (any region) and exit 0.
//   --dry-run          print the generated module instead of writing it.
//
// Both sources are read into memory over HTTPS; nothing is cached on disk.

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const CLOVIS_URL = 'https://raw.githubusercontent.com/Cattn/clovis/main/client/src/lib/airports.ts';
const OURAIRPORTS_URL = 'https://davidmegginson.github.io/ourairports-data/airports.csv';
const OUT_FILE = fileURLToPath(new URL('../src/flights/northeast-airports.ts', import.meta.url));

/** US Census Bureau Northeast region. Every one of these states is on Eastern time. */
const NORTHEAST_REGIONS = ['US-CT', 'US-ME', 'US-MA', 'US-NH', 'US-RI', 'US-VT', 'US-NJ', 'US-NY', 'US-PA'];
const TIME_ZONE = 'America/New_York';
const TYPE_RANK = { large_airport: 0, medium_airport: 1, small_airport: 2 };

function parseArgs(argv) {
  const args = { lookup: [], dryRun: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--dry-run') args.dryRun = true;
    else if (argv[i] === '--lookup') args.lookup = (argv[++i] ?? '').split(',').map((s) => s.trim().toUpperCase()).filter(Boolean);
    else throw new Error(`Unknown argument: ${argv[i]}`);
  }
  return args;
}

async function fetchText(url) {
  const res = await fetch(url, { signal: AbortSignal.timeout(60_000) });
  if (!res.ok) throw new Error(`GET ${url} failed (${res.status})`);
  return res.text();
}

/** Clovis rows look like: ['ORD', 'Chicago', 'Chicago O\'Hare International Airport'], */
export function parseClovis(source) {
  const str = String.raw`'((?:[^'\\]|\\.)*)'`;
  const row = new RegExp(String.raw`\[\s*${str}\s*,\s*${str}\s*,\s*${str}\s*\]`, 'g');
  const unescape = (s) => s.replace(/\\(.)/g, '$1');
  const out = new Map();
  for (const m of source.matchAll(row)) {
    out.set(unescape(m[1]), { city: unescape(m[2]), name: unescape(m[3]) });
  }
  return out;
}

/** Minimal RFC 4180 parser: quoted fields, "" escapes, commas and newlines inside quotes. */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.filter((r) => r.length === header.length).map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

/** One OurAirports row per IATA code: skip closed airports, prefer large > medium > small. */
function indexByIata(rows) {
  const byIata = new Map();
  for (const r of rows) {
    if (!r.iata_code || r.type === 'closed') continue;
    const prev = byIata.get(r.iata_code);
    if (!prev || (TYPE_RANK[r.type] ?? 9) < (TYPE_RANK[prev.type] ?? 9)) byIata.set(r.iata_code, r);
  }
  return byIata;
}

const round4 = (n) => Math.round(Number(n) * 1e4) / 1e4;
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function render(entries) {
  const lines = entries.map((e) =>
    `  { iata: ${q(e.iata)}, name: ${q(e.name)}, city: ${q(e.city)}, region: ${q(e.region)}, coordinates: [${e.lng}, ${e.lat}], timeZone: ${q(TIME_ZONE)} },`
  );
  return `// GENERATED by apps/server/scripts/northeast-airports.mjs. Do not edit by hand; rerun the script.
//
// Codes, cities and names: Cattn/clovis client/src/lib/airports.ts (itself from OurAirports;
// large + scheduled-medium airports with IATA codes).
// Coordinates and region: OurAirports airports.csv (latitude_deg, longitude_deg, iso_region),
// https://ourairports.com/data/ (public domain). Rounded to 4 decimals, stored [lng, lat].
// Northeast = US Census Bureau Northeast region: ${NORTHEAST_REGIONS.join(', ')}.

import type { LngLat } from '@transit/shared';

export interface NortheastAirport {
  iata: string;
  name: string;
  city: string;
  /** ISO 3166-2 region, e.g. 'US-MA'. */
  region: string;
  coordinates: LngLat;
  /** IANA zone. Every Northeast state is on Eastern time. */
  timeZone: string;
}

export const NORTHEAST_AIRPORTS: readonly NortheastAirport[] = [
${lines.join('\n')}
];
`;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const [clovisSrc, csv] = await Promise.all([fetchText(CLOVIS_URL), fetchText(OURAIRPORTS_URL)]);
  const clovis = parseClovis(clovisSrc);
  const ourAirports = indexByIata(parseCsv(csv));
  if (clovis.size < 1000) throw new Error(`Parsed only ${clovis.size} Clovis airports; did the file format change?`);

  const entries = [];
  for (const [iata, { city, name }] of clovis) {
    const r = ourAirports.get(iata);
    if (!r || r.iso_country !== 'US' || !NORTHEAST_REGIONS.includes(r.iso_region)) continue;
    entries.push({ iata, name, city, region: r.iso_region, lat: round4(r.latitude_deg), lng: round4(r.longitude_deg) });
  }
  entries.sort((a, b) => a.iata.localeCompare(b.iata));

  const missing = [...clovis.keys()].filter((c) => !ourAirports.has(c));
  console.error(`Clovis: ${clovis.size} airports. OurAirports: ${ourAirports.size} IATA codes. Not in OurAirports: ${missing.length}.`);
  console.error(`Northeast: ${entries.length} airports (${entries.map((e) => e.iata).join(' ')})`);

  for (const code of args.lookup) {
    const r = ourAirports.get(code);
    console.log(r
      ? JSON.stringify({ iata: code, name: r.name, region: r.iso_region, coordinates: [round4(r.longitude_deg), round4(r.latitude_deg)] })
      : JSON.stringify({ iata: code, error: 'not in OurAirports' }));
  }

  const out = render(entries);
  if (args.dryRun) process.stdout.write(out);
  else {
    await writeFile(OUT_FILE, out, 'utf8');
    console.error(`Wrote ${OUT_FILE}`);
  }
}

if (import.meta.url === `file://${process.argv[1]}` || fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
